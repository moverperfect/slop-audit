"""Two generators that say they wrote a file, in words the marker table did not know.

The table read `@generated`, Go's `Code generated by` and the protobuf banner. Two TypeScript
generators sign their output in sentences of their own:

  `wrangler types` writes `worker-configuration.d.ts` into every Cloudflare Workers project
  that follows the documented setup, under `// Generated by Wrangler by running ...`. The file
  is the runtime's whole type surface, 16,435 lines on the Astro site audited on 2026-10-29,
  and it was that repository's largest god file, a quarter of its duplication and 365 of
  its type escapes.

  Kontent.ai's model generator heads every file `This file has been auto-generated by
  '@kontent-ai/...'`. Eighty-seven files on the same site.

Both phrases name the act of generating, so a hand-written file has no reason to open with
either. They are read in the header window only, like the others, so prose that mentions
them further down changes nothing.
"""

from __future__ import annotations

import pytest
from l1_analyzer import scope

_WRANGLER = (
    "/* eslint-disable */\n"
    "// Generated by Wrangler by running `wrangler types` (hash: 3e2a9bf7238a71a13c2c834aa1b03bc1)\n"
    "// Runtime types generated with workerd@1.20261019.1 2026-10-12 nodejs_compat\n"
    "interface Env {}\n"
)

_KONTENT = (
    "/*\n"
    " * This file has been auto-generated by '@kontent-ai/sync-sdk@9.1.1'.\n"
    " *\n"
    " * (c) Kontent.ai\n"
    " */\n"
    "export type Codename = 'a' | 'b';\n"
)


@pytest.mark.parametrize("name,text", [("worker-configuration.d.ts", _WRANGLER),
                                       ("main.generated.ts", _KONTENT)])
def test_a_typescript_generator_s_signature_scopes_the_file_out(tmp_path, name, text):
    made = tmp_path / name
    made.write_text(text)
    assert scope._bucket_reason(made, tmp_path, False, scope.PRODUCTION) == "generated"


def test_a_hand_written_file_that_mentions_wrangler_is_kept(tmp_path):
    """The phrase is the generator's signature, not the tool's name. A file about Wrangler is
    not a file Wrangler wrote."""
    written = tmp_path / "deploy.ts"
    written.write_text("// Deploys with Wrangler; see wrangler.jsonc.\nexport const target = 'production';\n")
    assert scope._bucket_reason(written, tmp_path, False, scope.PRODUCTION) is None
